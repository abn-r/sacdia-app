/// File names for payment receipts.
///
/// Pickers (camera, gallery) hand us temp names such as
/// `image_picker_9A085501-....png`. Those must never reach the backend or the
/// screen as-is.
library;

/// Name sent to the backend for a receipt taken with the camera or gallery:
/// `comprobante-<folio>.<ext>`. Falls back to `comprobante.<ext>` when the
/// folio is empty. Characters that are not safe in a file name are dropped.
String friendlyReceiptUploadName({
  required String folio,
  required String extension,
}) {
  final safeFolio = folio.replaceAll(RegExp(r'[^A-Za-z0-9_-]'), '');
  final ext = extension.replaceAll('.', '').toLowerCase();
  final base = safeFolio.isEmpty ? 'comprobante' : 'comprobante-$safeFolio';
  return ext.isEmpty ? base : '$base.$ext';
}

final _uuidName = RegExp(
  r'^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}(\.[A-Za-z0-9]+)?$',
);

/// True for names generated by the pickers/plugins (not chosen by the user).
bool isGeneratedReceiptName(String name) {
  final trimmed = name.trim();
  if (trimmed.isEmpty) return true;
  final lower = trimmed.toLowerCase();
  return lower.startsWith('image_picker_') ||
      lower.startsWith('scaled_') ||
      _uuidName.hasMatch(trimmed);
}

/// Name to show in the receipts list. Generated names are replaced by
/// [defaultLabel] ("Comprobante"), numbered with [position] (1-based) when the
/// order has [total] > 1 receipts. Real names are returned unchanged.
String receiptDisplayName({
  required String storedName,
  required String defaultLabel,
  required int position,
  required int total,
}) {
  if (!isGeneratedReceiptName(storedName)) return storedName;
  return total > 1 ? '$defaultLabel $position' : defaultLabel;
}
